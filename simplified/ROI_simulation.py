# =============================================================================
# ROI SIMULATION — Business case for the retention model
# =============================================================================
#
# Uses the churn dataset (with NBI columns) to answer:
#   1. How much NBI is concentrated in top clients?
#   2. What is the churn rate of top clients specifically?
#   3. How much NBI is lost to churn each year?
#   4. What would a 1pp churn reduction save?
#   5. Multi-scenario analysis (different reduction targets)
#   6. Cost-benefit: how much can we spend on retention and still profit?
#
# Prerequisite: `df` from data_processing.py with columns:
#   client_id, year, churned, nbi_annual (and optionally nbi_q1..q4)
# =============================================================================


# %% ---- CELL 1: Imports ----

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.ticker as mticker


# %% ---- CELL 2: Quick data check ----

print(f"Rows: {len(df)} | Years: {sorted(df['year'].unique())}")
print(f"Columns: {list(df.columns)}")
print(f"Overall churn rate: {df['churned'].mean():.2%}")

# Make sure we have NBI
assert "nbi_annual" in df.columns, "Need 'nbi_annual' column. Add NBI to your Stock CSVs."
print(f"Total annual NBI across all client-years: {df['nbi_annual'].sum():,.0f} EUR")


# %% ---- CELL 3: NBI concentration — what % of NBI comes from top X% of clients? ----

# We'll compute this per year and also overall
concentration_results = []

for year in sorted(df["year"].unique()):
    yd = df[df["year"] == year].copy()
    yd = yd.sort_values("nbi_annual", ascending=False)

    total_nbi = yd["nbi_annual"].sum()
    n_clients = len(yd)

    for pct in [1, 5, 10, 20, 50]:
        top_n = max(int(n_clients * pct / 100), 1)
        top_nbi = yd.head(top_n)["nbi_annual"].sum()
        concentration_results.append({
            "year": year,
            "top_pct": f"Top {pct}%",
            "n_clients": top_n,
            "nbi_sum": top_nbi,
            "pct_of_total_nbi": top_nbi / total_nbi * 100 if total_nbi else 0,
        })

concentration = pd.DataFrame(concentration_results)

# Display pivot
pivot = concentration.pivot_table(
    index="top_pct", columns="year", values="pct_of_total_nbi"
).reindex(["Top 1%", "Top 5%", "Top 10%", "Top 20%", "Top 50%"])

print("\n=== NBI CONCENTRATION ===")
print("What % of total NBI is generated by the top X% of clients?\n")
print(pivot.to_string(float_format="%.1f"))
print("\n(Values are % of total annual NBI)")


# %% ---- CELL 4: Plot — NBI concentration (Pareto curve) ----

fig, ax = plt.subplots(figsize=(9, 6))

for year in sorted(df["year"].unique()):
    yd = df[df["year"] == year].sort_values("nbi_annual", ascending=False)
    cumulative_nbi = yd["nbi_annual"].cumsum() / yd["nbi_annual"].sum() * 100
    cumulative_clients = np.arange(1, len(yd) + 1) / len(yd) * 100
    ax.plot(cumulative_clients, cumulative_nbi, lw=2, label=str(year))

ax.plot([0, 100], [0, 100], "--", color="gray", alpha=0.5, label="Perfect equality")
ax.axvline(10, color="red", ls=":", alpha=0.5)
ax.axhline(70, color="red", ls=":", alpha=0.5)
ax.set_xlabel("% of clients (ranked by NBI)")
ax.set_ylabel("% of total NBI")
ax.set_title("NBI Concentration (Lorenz Curve)")
ax.legend()
ax.grid(alpha=0.3)
plt.tight_layout()
plt.show()


# %% ---- CELL 5: Churn rate by NBI segment ----
# Are top clients churning at the same rate as the rest?

segment_results = []

for year in sorted(df["year"].unique()):
    yd = df[df["year"] == year].copy()
    yd = yd.sort_values("nbi_annual", ascending=False)
    n = len(yd)

    # Define segments
    segments = {
        "Top 1%":    yd.head(max(int(n * 0.01), 1)),
        "Top 5%":    yd.head(max(int(n * 0.05), 1)),
        "Top 10%":   yd.head(max(int(n * 0.10), 1)),
        "Top 20%":   yd.head(max(int(n * 0.20), 1)),
        "Bottom 50%": yd.tail(int(n * 0.50)),
        "All":       yd,
    }

    for seg_name, seg_df in segments.items():
        seg_churn = seg_df["churned"].mean()
        seg_nbi = seg_df["nbi_annual"].sum()
        seg_mean_nbi = seg_df["nbi_annual"].mean()
        segment_results.append({
            "year": year,
            "segment": seg_name,
            "n_clients": len(seg_df),
            "churn_rate": seg_churn,
            "total_nbi": seg_nbi,
            "mean_nbi": seg_mean_nbi,
        })

segments_df = pd.DataFrame(segment_results)

print("\n=== CHURN RATE BY NBI SEGMENT ===\n")
for year in sorted(df["year"].unique()):
    print(f"--- {year} ---")
    yr = segments_df[segments_df["year"] == year]
    print(yr[["segment", "n_clients", "churn_rate", "mean_nbi", "total_nbi"]].to_string(
        index=False,
        formatters={
            "churn_rate": "{:.2%}".format,
            "mean_nbi": "{:,.0f}".format,
            "total_nbi": "{:,.0f}".format,
        }
    ))
    print()


# %% ---- CELL 6: NBI lost to churn each year ----
# For each year: sum of NBI of clients who churned

nbi_lost = []

for year in sorted(df["year"].unique()):
    yd = df[df["year"] == year]
    total_nbi = yd["nbi_annual"].sum()
    churned_clients = yd[yd["churned"] == 1]
    lost_nbi = churned_clients["nbi_annual"].sum()
    n_churned = len(churned_clients)

    nbi_lost.append({
        "year": year,
        "total_nbi": total_nbi,
        "lost_nbi": lost_nbi,
        "n_churned": n_churned,
        "pct_nbi_lost": lost_nbi / total_nbi * 100 if total_nbi else 0,
        "avg_nbi_per_churned": lost_nbi / n_churned if n_churned else 0,
    })

lost_df = pd.DataFrame(nbi_lost)

print("\n=== NBI LOST TO CHURN ===\n")
print(lost_df.to_string(index=False, formatters={
    "total_nbi": "{:,.0f}".format,
    "lost_nbi": "{:,.0f}".format,
    "pct_nbi_lost": "{:.1f}%".format,
    "avg_nbi_per_churned": "{:,.0f}".format,
}))


# %% ---- CELL 7: Impact of reducing churn by 1pp ----
# If we reduce churn from Y% to (Y-1)%, how many clients are saved
# and how much NBI is preserved?

print("\n=== IMPACT OF 1 PERCENTAGE POINT CHURN REDUCTION ===\n")

for year in sorted(df["year"].unique()):
    yd = df[df["year"] == year].copy()
    n_total = len(yd)
    current_churn_rate = yd["churned"].mean()
    current_churned = yd[yd["churned"] == 1]

    # Clients saved = 1% of total portfolio
    clients_saved = int(n_total * 0.01)

    # Which clients would we save? The ones with highest NBI among churned
    # (a good model targets the most valuable at-risk clients first)
    churned_sorted = current_churned.sort_values("nbi_annual", ascending=False)
    saved_clients = churned_sorted.head(clients_saved)
    nbi_preserved = saved_clients["nbi_annual"].sum()
    avg_nbi_saved = saved_clients["nbi_annual"].mean()

    print(f"--- {year} ---")
    print(f"  Current churn rate : {current_churn_rate:.2%}")
    print(f"  Target churn rate  : {current_churn_rate - 0.01:.2%}")
    print(f"  Clients saved      : {clients_saved:,}")
    print(f"  NBI preserved      : {nbi_preserved:,.0f} EUR")
    print(f"  Avg NBI per saved  : {avg_nbi_saved:,.0f} EUR")
    print(f"  -> This is {nbi_preserved / yd['nbi_annual'].sum() * 100:.2f}% of total portfolio NBI")
    print()


# %% ---- CELL 8: Multi-scenario table ----
# What if we reduce churn by 0.5pp, 1pp, 2pp, 3pp?

scenarios = []

for year in sorted(df["year"].unique()):
    yd = df[df["year"] == year].copy()
    n_total = len(yd)
    total_nbi = yd["nbi_annual"].sum()
    current_churn = yd["churned"].mean()
    churned_sorted = yd[yd["churned"] == 1].sort_values("nbi_annual", ascending=False)

    for reduction_pp in [0.5, 1.0, 1.5, 2.0, 3.0]:
        clients_saved = int(n_total * reduction_pp / 100)
        clients_saved = min(clients_saved, len(churned_sorted))  # can't save more than churned

        saved = churned_sorted.head(clients_saved)
        nbi_preserved = saved["nbi_annual"].sum()

        scenarios.append({
            "year": year,
            "reduction_pp": f"{reduction_pp}pp",
            "new_churn_rate": f"{(current_churn - reduction_pp/100):.2%}",
            "clients_saved": clients_saved,
            "nbi_preserved_eur": nbi_preserved,
            "pct_portfolio_nbi": nbi_preserved / total_nbi * 100,
        })

scenarios_df = pd.DataFrame(scenarios)

print("\n=== MULTI-SCENARIO: CHURN REDUCTION IMPACT ===")
print("(Assuming model targets highest-NBI churned clients first)\n")
for year in sorted(df["year"].unique()):
    print(f"--- {year} ---")
    yr = scenarios_df[scenarios_df["year"] == year]
    print(yr[["reduction_pp", "new_churn_rate", "clients_saved", "nbi_preserved_eur", "pct_portfolio_nbi"]].to_string(
        index=False,
        formatters={
            "nbi_preserved_eur": "{:,.0f}".format,
            "pct_portfolio_nbi": "{:.2f}%".format,
        }
    ))
    print()


# %% ---- CELL 9: Plot — NBI preserved per scenario ----

fig, ax = plt.subplots(figsize=(10, 6))

