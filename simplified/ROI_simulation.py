# %% ---- CELL 10: Cost-benefit — maximum retention budget ----
# How much can we spend per saved client and still break even?
# Rule of thumb: retention cost should be < 50% of the NBI we preserve

print("\n=== COST-BENEFIT: MAX RETENTION SPEND ===")
print("(Assuming intervention cost must be < NBI preserved to be profitable)\n")

for year in sorted(df["year"].unique()):
    yd = df[df["year"] == year].copy()
    n_total = len(yd)
    churned_sorted = yd[yd["churned"] == 1].sort_values("nbi_annual", ascending=False)

    # 1pp reduction scenario
    clients_saved = int(n_total * 0.01)
    clients_saved = min(clients_saved, len(churned_sorted))
    saved = churned_sorted.head(clients_saved)
    nbi_preserved = saved["nbi_annual"].sum()
    avg_nbi = saved["nbi_annual"].mean()

    print(f"--- {year} (1pp reduction) ---")
    print(f"  Clients to target    : {clients_saved:,}")
    print(f"  NBI preserved (total): {nbi_preserved:,.0f} EUR")
    print(f"  Avg NBI per client   : {avg_nbi:,.0f} EUR")
    print(f"  Max spend per client : {avg_nbi * 0.50:,.0f} EUR  (50% of NBI)")
    print(f"  Max total budget     : {nbi_preserved * 0.50:,.0f} EUR  (50% of preserved NBI)")
    print(f"  -> ROI at 50% cost   : 2x (spend 1 EUR, keep 2 EUR of NBI)")
    print()


# %% ---- CELL 11: 3-year cumulative impact (CLV perspective) ----
# A saved client doesn't just generate NBI in year 1 — they stay for multiple years.
# Using the KM survival from H3: [0.92, 0.86, 0.82]

SURVIVAL_RATES = [0.92, 0.86, 0.82]  # from your H3 results
DISCOUNT_RATE = 0.05  # 5% annual discount rate

print("\n=== 3-YEAR CUMULATIVE IMPACT (CLV VIEW) ===")
print(f"Survival rates from H3: {SURVIVAL_RATES}")
print(f"Discount rate: {DISCOUNT_RATE:.0%}\n")

for year in sorted(df["year"].unique()):
    yd = df[df["year"] == year].copy()
    n_total = len(yd)
    churned_sorted = yd[yd["churned"] == 1].sort_values("nbi_annual", ascending=False)

    # 1pp reduction
    clients_saved = int(n_total * 0.01)
    clients_saved = min(clients_saved, len(churned_sorted))
    saved = churned_sorted.head(clients_saved)
    avg_nbi = saved["nbi_annual"].mean()

    # 3-year value of each saved client (discounted, with survival)
    clv_per_client = 0
    for t, s_t in enumerate(SURVIVAL_RATES, start=1):
        clv_per_client += avg_nbi * s_t / (1 + DISCOUNT_RATE) ** t

    total_3yr_value = clv_per_client * clients_saved

    print(f"--- {year} (1pp reduction, {clients_saved} clients saved) ---")
    print(f"  Avg NBI per saved client  : {avg_nbi:>12,.0f} EUR / year")
    print(f"  Year 1 value              : {avg_nbi * SURVIVAL_RATES[0] / (1+DISCOUNT_RATE):>12,.0f} EUR")
    print(f"  Year 2 value              : {avg_nbi * SURVIVAL_RATES[1] / (1+DISCOUNT_RATE)**2:>12,.0f} EUR")
    print(f"  Year 3 value              : {avg_nbi * SURVIVAL_RATES[2] / (1+DISCOUNT_RATE)**3:>12,.0f} EUR")
    print(f"  3-year CLV per client     : {clv_per_client:>12,.0f} EUR")
    print(f"  Total 3-year value saved  : {total_3yr_value:>12,.0f} EUR")
    print()


